/// Something that happened in a session. Journaled in order; never edited.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "type", rename_all = "camelCase", rename_all_fields = "camelCase")]
#[ts(export)]
pub enum Event {
    SessionStarted {
        /// Journal format version.
        format: u32,
        cwd: String,
        strive_version: String,
    },
    UserMessage {
        text: String,
    },
    /// Opening the journal found a partial last line from a crash and
    /// discarded it.
    Recovered {
        discarded_bytes: u64,
    },
    /// The session's spending limits from here on. `None` means unlimited.
    BudgetSet {
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        usd_micros: Option<u64>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        tokens: Option<u64>,
    },
    /// A model request was admitted against the budget and sent upstream.
    /// Written before sending, so a crash mid-call still counts it.
    ModelCallStarted {
        /// Numbers this session's calls; pairs with `ModelCallFinished`.
        call: u64,
        provider: String,
        model: String,
        /// The exact request body sent upstream.
        request: Digest,
        /// The most this call can cost, held until it finishes.
        reserved_usd_micros: u64,
        reserved_tokens: u64,
    },
    ModelCallFinished {
        call: u64,
        outcome: CallOutcome,
        /// The exact response bytes received, when any were.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        response: Option<Digest>,
        duration_ms: u64,
    },
    /// The daemon is about to perform a change or command for the agent.
    /// Written first, so an effect cut off by a crash is still on record.
    EffectStarted {
        /// Numbers this session's effects; pairs with `EffectFinished`.
        effect: u64,
        /// The model's tool call this effect serves.
        call_id: String,
        record: EffectRecord,
    },
    EffectFinished {
        effect: u64,
        outcome: EffectOutcome,
        duration_ms: u64,
    },
    /// What the agent may do without asking, from here on.
    ApprovalModeSet {
        mode: ApprovalMode,
    },
    /// An effect waits for a person to allow or decline it.
    ApprovalRequested {
        effect: u64,
        description: String,
    },
    ApprovalDecided {
        effect: u64,
        decision: Decision,
        /// The client that decided.
        by: String,
    },
    /// The workspace's files were saved (outside the user's own git).
    Checkpointed {
        checkpoint: u64,
        /// The commit in the session's shadow repository.
        commit: String,
    },
    /// The workspace was put back to a checkpoint; the files as they were
    /// just before are checkpoint `saved_as`, so this can be undone.
    Rewound {
        to: u64,
        saved_as: u64,
    },
    /// The agent began working on the session's prompts.
    TurnStarted {
        turn: u64,
        /// The last prompt this turn took: later ones wait for the next turn,
        /// even if they were journaled before this entry.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        through_seq: Option<u64>,
    },
    /// The model's reply within a turn.
    AssistantMessage {
        turn: u64,
        /// The reply's text, for showing.
        text: String,
        /// The tools it called; their results are the effects with these ids.
        tool_calls: Vec<ToolCall>,
        /// The message exactly as the agent keeps it, fed back on resume.
        #[ts(type = "unknown")]
        message: serde_json::Value,
    },
    TurnEnded {
        turn: u64,
        reason: TurnEnd,
    },
    /// The project context an agent host was given when it started.
    ContextLoaded {
        instructions: Vec<ContextFile>,
        skills: Vec<String>,
        /// MCP servers from settings, and how each started.
        #[serde(default)]
        mcp: Vec<McpStatus>,
    },
    /// The conversation up to entry `upto_seq` was summarized; from here on
    /// the agent carries the summary instead of those messages.
    Compacted {
        upto_seq: u64,
        summary: String,
    },
}

