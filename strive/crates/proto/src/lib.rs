/// How an effect ended. `output` is what the agent is shown.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "kind", rename_all = "camelCase", rename_all_fields = "camelCase")]
#[ts(export)]
pub enum EffectOutcome {
    /// It ran. For bash, `exit_code` is the command's status (absent if it
    /// was killed by the timeout).
    Done {
        output: Digest,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        exit_code: Option<i32>,
        /// The output was cut to fit; the full output isn't kept.
        truncated: bool,
    },
    /// It was not allowed, or could not be done; `reason` says why.
    Refused { reason: String },
    /// The daemon stopped while it ran; whatever it changed stays changed.
    Interrupted,
}
/// How a model call ended, and what it cost.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "kind", rename_all = "camelCase", rename_all_fields = "camelCase")]
#[ts(export)]
pub enum CallOutcome {
    /// The provider reported usage; the cost is exact.
    Complete { status: u16, usage: Usage, cost_usd_micros: u64 },
    /// The provider refused the request before doing work (an error status).
    Rejected { status: u16 },
    /// The call broke after it may have been billed. It is charged the full
    /// reservation, since the real cost is unknown.
    Broken { reason: String, cost_usd_micros: u64, tokens: u64 },
}

/// Tokens a call used, as the provider reported them.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct Usage {
    pub input: u64,
    pub output: u64,
    /// Cache writes at the standard (five-minute) rate.
    pub cache_write: u64,
    /// Cache writes kept for an hour, at their higher rate.
    #[serde(default)]
    pub cache_write_long: u64,
    pub cache_read: u64,
}

impl Usage {
    pub fn total(&self) -> u64 {
        self.input
            .saturating_add(self.output)
            .saturating_add(self.cache_write)
            .saturating_add(self.cache_write_long)
            .saturating_add(self.cache_read)
    }
}

