"""Resolves pyproject.toml's dependencies against the index mirror and writes tally.lock.

    python3 tools/lock.py           # write tally.lock
    python3 tools/lock.py --check   # exit 1 if tally.lock is out of date

A dependency is `name==version` or `name>=version` (the newest that
matches). What a package requires is locked too.
"""

from __future__ import annotations

import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "tally.lock"
SPEC = re.compile(r"^([a-z0-9][a-z0-9-]*)\s*(==|>=)\s*([0-9][0-9.]*)$")


def version_key(v: str) -> tuple[int, ...]:
    return tuple(int(p) for p in v.split("."))


def pick(index: dict, spec: str, wanted_by: str) -> tuple[str, str]:
    m = SPEC.match(spec.strip())
    if not m:
        sys.exit(f"{wanted_by}: can't read the dependency {spec!r} (want name==version or name>=version)")
    name, op, version = m.groups()
    versions = index["packages"].get(name)
    if versions is None:
        sys.exit(f"{wanted_by}: {name} isn't in the index mirror (vendor/index.json)")
    if op == "==":
        if version not in versions:
            sys.exit(f"{wanted_by}: {name} has no version {version} in the index mirror")
        return name, version
    matching = [v for v in versions if version_key(v) >= version_key(version)]
    if not matching:
        sys.exit(f"{wanted_by}: no version of {name} is {op}{version}")
    return name, max(matching, key=version_key)


def resolve() -> str:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())
    index = json.loads((ROOT / project["tool"]["tally"]["lock"]["index"]).read_text())
    locked: dict[str, tuple[str, str]] = {}
    queue = [(spec, "pyproject.toml") for spec in project["project"]["dependencies"]]
    while queue:
        spec, wanted_by = queue.pop(0)
        name, version = pick(index, spec, wanted_by)
        if name in locked:
            continue
        locked[name] = (version, wanted_by)
        queue += [(req, name) for req in index["packages"][name][version]["requires"]]
    lines = ["# Generated by tools/lock.py from pyproject.toml. Do not edit: run ./dev lock."]
    for name in sorted(locked):
        version, wanted_by = locked[name]
        sha = index["packages"][name][version]["sha256"]
        via = "" if wanted_by == "pyproject.toml" else f"  # via {wanted_by}"
        lines.append(f"{name}=={version} --hash=sha256:{sha}{via}")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = resolve()
    if "--check" in sys.argv:
        if not LOCK.exists() or LOCK.read_text() != text:
            print("tally.lock doesn't match pyproject.toml: run ./dev lock", file=sys.stderr)
            return 1
        return 0
    LOCK.write_text(text)
    print("wrote tally.lock")
    return 0


if __name__ == "__main__":
    sys.exit(main())
