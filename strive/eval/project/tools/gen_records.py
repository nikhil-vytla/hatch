"""Generates tally/_generated/records.py from schema/records.def.

    python3 tools/gen_records.py           # write it
    python3 tools/gen_records.py --check   # exit 1 if it's out of date
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "schema" / "records.def"
OUT = ROOT / "tally" / "_generated" / "records.py"

FIELD = re.compile(r"^\s+(\w+):\s*([\w\[\]]+)(\?)?(?:\s*=\s*(.+))?$")
PY_TYPES = {"str": "str", "int": "int", "bool": "bool", "decimal": "Decimal", "date": "date"}


def parse(text: str) -> list[tuple[str, list[tuple[str, str, bool, str | None]]]]:
    records: list[tuple[str, list[tuple[str, str, bool, str | None]]]] = []
    for n, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line.startswith("record "):
            records.append((line.split()[1], []))
            continue
        m = FIELD.match(line)
        if not m or not records:
            sys.exit(f"schema/records.def:{n}: can't read {line.strip()!r}")
        name, kind, optional, default = m.groups()
        records[-1][1].append((name, kind, bool(optional), default))
    return records


def py_type(kind: str) -> str:
    if kind.startswith("list[") and kind.endswith("]"):
        return f"list[{kind[5:-1]}]"
    if kind not in PY_TYPES:
        sys.exit(f"schema/records.def: unknown type {kind}")
    return PY_TYPES[kind]


def field_line(name: str, kind: str, optional: bool, default: str | None) -> str:
    t = py_type(kind)
    if optional:
        return f"    {name}: {t} | None = None"
    if default is None:
        return f"    {name}: {t}"
    if kind.startswith("list["):
        return f"    {name}: {t} = field(default_factory=list)"
    if kind == "decimal":
        return f'    {name}: {t} = Decimal("{default}")'
    return f"    {name}: {t} = {default}"


def from_row_value(name: str, kind: str, optional: bool) -> str:
    get = f"row[{name!r}]" if not optional else f"row.get({name!r})"
    if kind == "decimal":
        conv = f"Decimal({get})"
    elif kind == "date":
        conv = f"date.fromisoformat({get})"
    elif kind.startswith("list["):
        conv = f"[{kind[5:-1]}.from_row(r) for r in {get}]"
    else:
        conv = get
    if optional and conv != get:
        return f"None if {get} is None else {conv}"
    return conv


def to_row_value(name: str, kind: str, optional: bool) -> str:
    v = f"self.{name}"
    if kind == "decimal":
        conv = f"str({v})"
    elif kind == "date":
        conv = f"{v}.isoformat()"
    elif kind.startswith("list["):
        conv = f"[x.to_row() for x in {v}]"
    else:
        return v
    return f"None if {v} is None else {conv}" if optional else conv


def generate(text: str) -> str:
    records = parse(text)
    out = [
        "# Generated by tools/gen_records.py from schema/records.def. Do not edit:",
        "# change the schema and run ./dev gen.",
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass, field",
        "from datetime import date",
        "from decimal import Decimal",
        "",
        f"__all__ = {sorted(name for name, _ in records)!r}".replace("'", '"'),
    ]
    for name, fields in records:
        required = [f for f in fields if not f[2] and f[3] is None]
        rest = [f for f in fields if f[2] or f[3] is not None]
        out += ["", "", "@dataclass", f"class {name}:"]
        out += [field_line(*f) for f in required + rest]
        out += ["", "    @classmethod", f"    def from_row(cls, row: dict) -> {name}:", "        return cls("]
        out += [f"            {f[0]}={from_row_value(f[0], f[1], f[2])}," for f in fields]
        out += ["        )", "", "    def to_row(self) -> dict:", "        return {"]
        out += [f"            {f[0]!r}: {to_row_value(f[0], f[1], f[2])}," for f in fields]
        out += ["        }"]
    return "\n".join(out).replace("'", '"') + "\n"


def main() -> int:
    code = generate(SCHEMA.read_text())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != code:
            print("tally/_generated/records.py is stale: run ./dev gen", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(code)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
