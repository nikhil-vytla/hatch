async (page) => {
  await page.goto("http://127.0.0.1:5193/#experiment/ghost-brush");
  await page.reload();
  await page.emulateMedia({ reducedMotion: "no-preference" });
  const checks = [];
  const ensure = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
  await page.getByRole("button", { name: "Pause sample animation" }).click();
  const sheet = page.getByRole("application");
  await sheet.scrollIntoViewIfNeeded();
  const box = await sheet.boundingBox();
  const before = await page.locator(".gb-counter").textContent();
  await page.mouse.move(box.x + box.width * .25, box.y + box.height * .5);
  await page.mouse.down();
  for (let i = 0; i <= 30; i++) { const t = i / 30; await page.mouse.move(box.x + box.width * (.25 + t * .55), box.y + box.height * (.48 + Math.sin(t * Math.PI * 3) * .18)); }
  await page.mouse.up();
  ensure(await page.locator(".gb-counter").textContent() !== before, "pointer stroke committed");
  const pointerCount = Number((await page.locator(".gb-counter").textContent()).match(/\d+/)[0]);
  await sheet.focus(); await page.keyboard.press("Space");
  for (let i = 0; i < 8; i++) await page.keyboard.press("ArrowRight");
  for (let i = 0; i < 5; i++) await page.keyboard.press("ArrowDown");
  await page.keyboard.press("Space");
  ensure(Number((await page.locator(".gb-counter").textContent()).match(/\d+/)[0]) === pointerCount + 1, "keyboard stroke committed");
  await page.getByRole("button", { name: "Undo stroke" }).click();
  ensure(Number((await page.locator(".gb-counter").textContent()).match(/\d+/)[0]) === pointerCount, "undo hides one completed stroke");
  await page.getByRole("button", { name: "Redo stroke" }).click();
  await page.locator(".gb-history > summary").click();
  await page.getByRole("textbox", { name: "Variant name" }).fill("Browser checkpoint");
  await page.getByRole("button", { name: "Preserve", exact: true }).click();
  await page.getByRole("button", { name: "Golden dust", exact: true }).click();
  await page.getByRole("button", { name: "Local preview", exact: true }).click();
  ensure((await page.locator(".gb-source").textContent()).includes("Local tag match"), "local selection is labeled separately");
  await page.getByRole("button", { name: "Draw a sample" }).click();
  await page.getByRole("button", { name: /Browser checkpoint/ }).click();
  ensure(Number((await page.locator(".gb-counter").textContent()).match(/\d+/)[0]) === pointerCount + 1, "restore returns to the saved stroke count");
  ensure(await page.locator(".gb-variants > button").count() >= 2, "restore preserves the abandoned sheet");
  await page.getByRole("button", { name: "Violet coral", exact: true }).click();
  ensure((await page.locator(".gb-source").textContent()).includes("Recorded Jev"), "recorded Jev has its own attribution");
  ensure((await page.locator(".gb-paper-top strong").textContent()) === "Coral nerve", "recorded result selects the saved winner");
  await page.getByRole("button", { name: "Compare one stroke" }).click();
  ensure(await page.locator(".gb-comparison-pair svg.gb-sample").count() === 2, "paired preview shows two replays");
  await page.getByRole("button", { name: "Ask Jev", exact: true }).click();
  ensure((await page.locator(".gb-status").textContent()).includes("Connect your Jev key"), "live request without a key stays local and explains the missing key");
  const svgDownload = page.waitForEvent("download"); await page.getByRole("button", { name: "Artwork SVG", exact: true }).click();
  ensure((await svgDownload).suggestedFilename() === "ghost-brush.svg", "artwork SVG downloads");
  const evidenceDownload = page.waitForEvent("download"); await page.getByRole("button", { name: "Stroke & decision evidence" }).click();
  ensure((await evidenceDownload).suggestedFilename() === "ghost-brush-evidence.json", "stroke and judgment evidence downloads");
  await page.getByRole("button", { name: "dark theme", exact: true }).click();
  await page.locator(".ghost-brush").scrollIntoViewIfNeeded();
  await page.screenshot({ path: "output/playwright/ghost-brush-dark.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "light theme", exact: true }).click();
  await page.locator(".gb-paper").scrollIntoViewIfNeeded();
  ensure(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "390px layout has no horizontal overflow");
  await page.screenshot({ path: "output/playwright/ghost-brush-mobile.png", fullPage: true });
  await page.emulateMedia({ reducedMotion: "reduce" });
  ensure(await page.locator(".gb-sample.animated").count() === 0, "reduced motion removes animated sample classes");
  return { checks, count: checks.length, realModelCallsDuringBrowserQA: 0 };
}
