async (page) => {
  const checks = [], requests = [];
  page.on("request", request => { if (request.url().includes("/api/evaluate")) requests.push(request.url()); });
  const ensure = (ok, name) => { if (!ok) throw new Error(name); checks.push(name); };
  const tick = () => page.locator(".live-world-preview").getAttribute("data-world-tick");
  await page.locator(".hero-window").scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector(".live-world-preview")?.getAttribute("data-preview-state") === "running");
  const moving = await tick(); await page.waitForTimeout(220);
  ensure(await tick() !== moving, "visible local preview advances");
  await page.locator("footer").scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector(".live-world-preview")?.getAttribute("data-preview-state") === "offscreen");
  const offscreen = await tick(); await page.waitForTimeout(220);
  ensure(await tick() === offscreen, "offscreen preview stops its world clock");
  await page.locator(".hero-window").scrollIntoViewIfNeeded();
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.waitForFunction(() => document.querySelector(".live-world-preview")?.getAttribute("data-preview-state") === "reduced-motion");
  const reduced = await tick(); await page.waitForTimeout(220);
  ensure(await tick() === reduced, "reduced motion leaves a static courtyard");
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.waitForFunction(() => document.querySelector(".live-world-preview")?.getAttribute("data-preview-state") === "running");
  await page.evaluate(() => { Object.defineProperty(document, "hidden", { configurable: true, get: () => true }); document.dispatchEvent(new Event("visibilitychange")); });
  const hidden = await tick(); await page.waitForTimeout(220);
  ensure(await tick() === hidden, "hidden-document listener stops its world clock, explicit visibility fixture");
  await page.evaluate(() => { delete document.hidden; document.dispatchEvent(new Event("visibilitychange")); });
  await page.waitForFunction(() => document.querySelector(".live-world-preview")?.getAttribute("data-preview-state") === "running");
  ensure(await page.locator(".mini-experiment-preview").count() === 7, "all seven new card previews render");
  ensure(await page.locator(".mini-experiment-preview[aria-hidden=true]").count() === 7, "card SVGs are decorative");
  ensure(await page.locator(".live-world-preview button,.live-world-preview a,.live-world-preview input").count() === 0, "hero preview has no nested interactive controls");
  ensure(await page.evaluate(async () => (await import("/src/live-world-preview.tsx")).MiniExperimentPreview({ kind: "unknown-kind" }) === null), "unknown preview kinds return null");
  await page.screenshot({ path: "output/playwright/home-preview-desktop.png" });
  await page.getByRole("button", { name: "dark theme", exact: true }).click();
  await page.screenshot({ path: "output/playwright/home-preview-dark.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "light theme", exact: true }).click();
  await page.locator(".hero-window").scrollIntoViewIfNeeded();
  ensure(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "390px homepage has no horizontal overflow");
  await page.screenshot({ path: "output/playwright/home-preview-mobile.png" });
  ensure(requests.length === 0, "preview lifecycle makes no model requests");
  return { checks, count: checks.length, modelRequests: requests.length };
}
