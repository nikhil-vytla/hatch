async (page) => {
  const results = {};
  const check = (name, value) => { if (!value) throw new Error(name); results[name] = value; };
  await page.getByRole('button', { name: 'Experiments', exact: true }).click();
  await page.getByRole('searchbox', { name: 'Find an experiment or capability' }).fill('Model Routing Lab');
  check('search_one_result', await page.locator('#count').textContent() === '1 of 41 experiments');
  await page.getByRole('button', { name: 'Model Routing Lab Agents & tooling', exact: true }).click();
  check('route_selected', await page.getByRole('heading', { name: 'Model Routing Lab', exact: true }).count() === 1);
  check('selection_keeps_focus', await page.evaluate(() => document.activeElement?.getAttribute('data-experiment') === 'routing'));
  check('heuristic_visible', (await page.locator('#detail').textContent()).includes('Default browser execution does not call Jev.'));
  await page.getByRole('searchbox').fill('a phrase with no matches');
  check('empty_search', await page.getByText('No matching experiments.', { exact: true }).isVisible());
  check('empty_search_clears_detail', await page.locator('#detail h2').count() === 0);
  await page.getByRole('searchbox').fill('probabilities');
  check('probabilities_search', await page.locator('#experiment-list button').count() > 0);
  await page.getByRole('searchbox').fill('');
  await page.getByRole('combobox', { name: 'Category', exact: true }).selectOption('Training & local');
  check('category_five', await page.locator('#count').textContent() === '5 of 41 experiments');
  await page.getByRole('combobox').selectOption('');
  await page.getByRole('button', { name: 'The missing structure', exact: true }).focus();
  await page.keyboard.press('Enter');
  check('keyboard_view_switch', await page.getByRole('heading', { name: 'The shape of the question matters.', exact: true }).isVisible());
  const examples = await page.locator('.compare pre').allTextContents();
  check('valid_question_examples', examples.length === 2 && examples.every(value => JSON.parse(value).type === 'choice'));
  await page.setViewportSize({ width: 390, height: 844 });
  check('mobile_structure_no_page_overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  check('mobile_examples_show_complete_lines', await page.locator('.compare pre').evaluateAll(elements => elements.every(el => el.scrollWidth <= el.clientWidth + 1)));
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' });
  check('dark_mode', await page.evaluate(() => getComputedStyle(document.body).backgroundColor === 'rgb(23, 29, 25)'));
  check('reduced_motion', await page.evaluate(() => matchMedia('(prefers-reduced-motion: reduce)').matches));
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: 'output/playwright/jev-capability-atlas-mobile-dark.png', fullPage: true });
  await page.getByRole('button', { name: 'Experiments', exact: true }).click();
  check('mobile_experiments_no_page_overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  const downloadPromise = page.waitForEvent('download');
  check('download_touch_target', await page.getByRole('button', { name: 'Download the audit data', exact: true }).evaluate(el => el.getBoundingClientRect().height >= 44));
  await page.getByRole('button', { name: 'Download the audit data', exact: true }).click();
  const download = await downloadPromise;
  check('download_name', download.suggestedFilename() === 'jev-capability-atlas.json');
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'no-preference' });
  await page.getByRole('searchbox').fill('Material sandbox');
  await page.getByRole('button', { name: 'Material sandbox Games & simulations', exact: true }).click();
  await page.getByRole('searchbox').fill('');
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: 'output/playwright/jev-capability-atlas-desktop.png', fullPage: true });
  check('complete_catalog', await page.locator('#experiment-list button').count() === 41);
  return results;
}
