async (page) => {
  const results = {};
  const check = (name, value) => { if (!value) throw new Error(name); results[name] = value; };
  const metadata = await page.evaluate(async () => (await fetch('/capability-build.json', { cache: 'no-store' })).json());
  const summary = page.locator('.jev-role summary');
  await summary.focus();
  await page.keyboard.press('Enter');
  check('keyboard_opens_inspector', await page.locator('.jev-role[open]').count() === 1);
  check('input_visible', await page.getByRole('heading', { name: 'What it sees', exact: true }).isVisible());
  check('model_scope_visible', (await page.locator('.jev-role').textContent()).includes('The particle grid is not supplied.'));
  check('execution_modes_visible', (await page.locator('.jev-role-modes').textContent()).includes('Implemented BYOK rule proposal'));
  check('atlas_deep_link', await page.locator('.jev-role a').getAttribute('href') === '/capabilities.html#materials');
  check('atlas_link_touch_target', await page.locator('.jev-role a').evaluate(el => el.getBoundingClientRect().height >= 44));
  await page.getByRole('button', { name: 'dark theme', exact: true }).click();
  check('dark_text', await page.locator('.jev-role-note').first().evaluate(el => getComputedStyle(el).color === 'rgb(173, 185, 172)'));
  await page.setViewportSize({ width: 390, height: 844 });
  check('mobile_inspector_fits', await page.locator('.jev-role').evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  await page.locator('.jev-role').screenshot({ path: 'output/playwright/jev-role-mobile-dark.png' });
  let releaseMetadata;
  const metadataReady = new Promise(resolve => { releaseMetadata = resolve; });
  await page.route('**/capability-build.json', async route => {
    await metadataReady;
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify({ ...metadata, records: { routing: true } }) });
  });
  await page.evaluate(() => { location.hash = '#experiment/routing'; });
  await page.getByRole('heading', { name: 'Model Routing Lab', exact: true, level: 1 }).waitFor();
  check('new_experiment_closes_inspector', await page.locator('.jev-role[open]').count() === 0);
  await page.locator('.jev-role summary').click();
  check('new_experiment_waits_for_own_metadata', await page.getByText('Checking the implementation snapshot…', { exact: true }).isVisible());
  check('previous_match_does_not_authorize_next_record', await page.getByRole('heading', { name: 'What it sees', exact: true }).count() === 0);
  releaseMetadata();
  await page.getByRole('heading', { name: 'What it sees', exact: true }).waitFor();
  await page.unroute('**/capability-build.json');
  check('new_experiment_correct_role', (await page.locator('.jev-role').textContent()).includes('Default browser execution does not call Jev.'));
  check('new_deep_link', await page.locator('.jev-role a').getAttribute('href') === '/capabilities.html#routing');
  await page.route('**/capability-build.json', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ ...metadata, records: { routing: false } }) }));
  await page.reload();
  await page.locator('.jev-role summary').click();
  await page.getByText('This build differs from the September 22 audit.', { exact: true }).waitFor();
  check('stale_snapshot_disclosed', await page.getByText('This build differs from the September 22 audit.', { exact: true }).isVisible());
  check('stale_claims_hidden', await page.getByRole('heading', { name: 'What it sees', exact: true }).count() === 0);
  await page.unroute('**/capability-build.json');
  await page.route('**/capability-build.json', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ ...metadata, buildId: '0'.repeat(64), records: { routing: true } }) }));
  await page.reload();
  await page.locator('.jev-role summary').click();
  await page.getByText('This build differs from the September 22 audit.', { exact: true }).waitFor();
  check('another_build_cannot_authorize_claims', await page.getByRole('heading', { name: 'What it sees', exact: true }).count() === 0);
  await page.unroute('**/capability-build.json');
  await page.reload();
  return results;
}
