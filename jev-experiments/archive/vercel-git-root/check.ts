import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
const origin = "https://jev-experiments.vercel.app";
const home = await fetch(origin);
assert.equal(home.status, 200);
assert((await home.text()).includes('id="root"'));
const evidence = await fetch(origin + "/data/judge.json");
assert.equal(evidence.status, 200);
const rows = (await evidence.json()).result.rows;
assert.equal(rows.length, 200);
assert(rows.every((row: any) => typeof row.question === "string" && typeof row.candidate_a === "string" && typeof row.candidate_b === "string"));
const companion = await fetch(origin + "/companion.zip");
assert.equal(companion.status, 200);
const zip = new Uint8Array(await companion.arrayBuffer());
assert.equal(zip[0], 0x50); assert.equal(zip[1], 0x4b); assert(zip.length > 1000);
const api = await fetch(origin + "/api/evaluate", { method: "POST", headers: { "Content-Type": "application/json" }, body: "{}" });
assert.equal(api.status, 401);
